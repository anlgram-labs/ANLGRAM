'use strict';
const fs = require('node:fs');
const path = require('node:path');
const {compileFunc} = require('../tests/settlement-runtime/node_modules/@ton-community/func-js');
const {Cell} = require('../tests/settlement-runtime/node_modules/@ton/core');

const contracts = path.join(__dirname, 'contracts');
const read = file => fs.readFileSync(path.join(contracts, file), 'utf8').replace(/\r\n/g, '\n');

async function compile(target, overrides = {}) {
  const result = await compileFunc({targets: [target], sources: file => overrides[file] ?? read(file)});
  if (result.status !== 'ok') throw Error(result.message);
  return {codeBocBase64: result.codeBoc, codeCellHash: Cell.fromBase64(result.codeBoc).hash().toString('hex')};
}

async function factoryArtifacts() {
  const standard = read('jetton-minter.fc');
  const receiver = '() recv_internal(';
  const mint = '    if (op == op::mint()) {';
  if (standard.split(receiver).length !== 2 || standard.split(mint).length !== 2) {
    throw Error('Factory minter derivation anchors changed');
  }
  const childSource = standard
    .replace(receiver, '#include "imports/factory-minter-bootstrap.fc";\n\n' + receiver)
    .replace(mint, `    if (bootstrap_factory_mint(op, query_id, sender_address, in_msg_body,
        total_supply, admin_address, content, jetton_wallet_code)) { return (); }

${mint}`);
  const childMinter = await compile('anlgram-factory-minter.fc', {'anlgram-factory-minter.fc': childSource});
  const jettonWallet = await compile('jetton-wallet.fc');
  const pins = `;; Generated by compile-factory.js.
const int FACTORY_MINTER_CODE_HASH = 0x${childMinter.codeCellHash};
const int FACTORY_WALLET_CODE_HASH = 0x${jettonWallet.codeCellHash};
`;
  const factory = await compile('anlgram-factory.fc', {'imports/factory-child-code.fc': pins});
  return {
    pins,
    artifact: {hex: factory.codeBocBase64, codeCellHash: factory.codeCellHash,
      childMinter, jettonWallet, financialDeploymentAuthorized: false}
  };
}

async function main() {
  const {pins, artifact} = await factoryArtifacts();
  const outputs = [
    [path.join(contracts, 'imports/factory-child-code.fc'), pins],
    [path.join(__dirname, 'build/anlgram-factory.compiled.json'), JSON.stringify(artifact, null, 2) + '\n']
  ];
  for (const [file, text] of outputs) {
    if (process.argv.includes('--check')) {
      if (fs.readFileSync(file, 'utf8').replace(/\r\n/g, '\n') !== text) {
        throw Error('Factory generation mismatch: ' + file);
      }
    } else {
      fs.writeFileSync(file, text);
    }
  }
  console.log(JSON.stringify({factory: artifact.codeCellHash, childMinter: artifact.childMinter.codeCellHash,
    jettonWallet: artifact.jettonWallet.codeCellHash, financialDeploymentAuthorized: false}));
}

if (require.main === module) main().catch(error => { console.error(error.message); process.exitCode = 1; });
module.exports = {factoryArtifacts};
