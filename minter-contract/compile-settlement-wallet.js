'use strict';
// Offline deterministic build. Never deploys or modifies the canonical wallet.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');
const { compileFunc } = require('@ton-community/func-js');
const { Cell } = require('@ton/core');
(async () => {
  const hashes = {};
  const result = await compileFunc({ targets: ['anlgram-settlement-wallet.fc'], sources: name => {
    const source = fs.readFileSync(path.join(__dirname,'contracts',name),'utf8').replace(/\r\n/g,'\n');
    hashes[name] = crypto.createHash('sha256').update(source).digest('hex'); return source;
  } });
  if (result.status !== 'ok') throw new Error(result.message);
  const cell = Cell.fromBase64(result.codeBoc), bytes = cell.toBoc();
  const hash = cell.hash().toString('hex');
  const artifact = JSON.stringify({ contract:'anlgram-settlement-wallet.fc', protocolVersion:1,
    codeBocBase64:result.codeBoc, codeHex:bytes.toString('hex'), codeCellHash:hash, codeHash:hash,
    bocFileSha256:crypto.createHash('sha256').update(bytes).digest('hex'),
    compilerPackageVersion:require('@ton-community/func-js/package.json').version,
    sourceFilesSha256:Object.fromEntries(Object.entries(hashes).sort(([a],[b])=>a.localeCompare(b))) },null,2);
  const pin = `;; Generated by compile-settlement-wallet.js; opt-in wallet only.\nconst int SETTLEMENT_WALLET_CODE_HASH = 0x${hash};\n`;
  const targets = [[path.join(__dirname,'build/anlgram-settlement-wallet.compiled.json'),artifact],
    [path.join(__dirname,'contracts/imports/settlement-wallet-code.fc'),pin]];
  for (const [file,content] of targets) {
    if (process.argv.includes('--check')) {
      if (fs.readFileSync(file,'utf8').replace(/\r\n/g,'\n') !== content) throw new Error('Non-reproducible artifact/pin: '+file);
    } else fs.writeFileSync(file,content);
  }
  console.log('Settlement wallet code cell:',hash);
  console.log('Settlement wallet BOC SHA-256:',JSON.parse(artifact).bocFileSha256);
})().catch(e=>{console.error(e);process.exitCode=1;});
